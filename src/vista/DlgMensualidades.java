    /**
    * Carga en la tabla todos los registros de mensualidades existentes.
    */
    public void mostrarDatos() {
    String[] columnas = {"Consecutivo", "Núm Alquiler", "Fecha Creación", "Inquilino", "Mes en Cobro", "Año", "Descuento", "Monto a pagar", "Estado"};
    model = new DefaultTableModel(null, columnas);
    tblMensualidades.setModel(model);

    for (Mensualidades m : listaMensualidades) {
        Object[] fila = {
            m.getConsecutivo(),
            m.getNumAlquiler(),
            m.getFechCreacion(),
            m.getNomInquilino(),
            m.getMesCobro(),
            m.getAnioActual(),
            m.getDescuento() + "%",
            m.getMontoMes(),
            m.getEstado()
            };
            model.addRow(fila);
        }
    }
    
    /**
    * Filtra los registros de la tabla según los criterios marcados
    * (Inquilino, Mes, Año) y el texto ingresado en el campo de búsqueda.
    */
    private void filtrar() {
    String texto = txtFiltro.getText().trim().toLowerCase();

    String[] columnas = {"Consecutivo", "Núm Alquiler", "Fecha Creación", "Inquilino", "Mes en Cobro", "Año", "Descuento", "Monto a pagar", "Estado"};
    model = new DefaultTableModel(null, columnas);
    tblMensualidades.setModel(model);

    for (Mensualidades m : listaMensualidades) {
        boolean coincide = true;

        if (chkInquilino.isSelected()) {
            coincide = coincide && m.getNomInquilino().toLowerCase().contains(texto);
        }
        if (chkMes.isSelected()) {
            coincide = coincide && String.valueOf(m.getMesCobro()).equals(texto);
        }
        if (chkAnio.isSelected()) {
            coincide = coincide && String.valueOf(m.getAnioActual()).equals(texto);
        }
        if (!chkInquilino.isSelected() && !chkMes.isSelected() && !chkAnio.isSelected()) {
            coincide = texto.isEmpty();
        }

        if (coincide) {
            Object[] fila = {
                m.getConsecutivo(),
                m.getNumAlquiler(),
                m.getFechCreacion(),
                m.getNomInquilino(),
                m.getMesCobro(),
                m.getAnioActual(),
                m.getDescuento() + "%",
                m.getMontoMes(),
                m.getEstado()
            };
            model.addRow(fila);
        }
    }
    }
    

