    /**
    * Genera las mensualidades del mes/año seleccionado para todos los
    * alquileres vigentes, validando que no existan duplicados ni fechas
    * anteriores a la actual, y refresca la tabla con los resultados.
    */
    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        int mes = cmbMesGenerar.getSelectedIndex() + 1;
    String textoAnio = txtAnioGenerar.getText().trim();

    if (textoAnio.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el año");
        return;
    }

    int anio;
    try {
        anio = Integer.parseInt(textoAnio);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número");
        return;
    }

    try {
        ArrayList<Mensualidades> generadas = Mensualidades.generarMensualidades(
                listaAlquileres, listaInquilinos, listaMensualidades, mes, anio);

        if (generadas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No se generaron mensualidades nuevas (ya existían o no hay alquileres vigentes)");
        } else {
            JOptionPane.showMessageDialog(this, "Se generaron " + generadas.size() + " mensualidades");
        }
        mostrarDatos();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnGenerarActionPerformed

