    /**
    * Filtra y muestra en la tabla únicamente las mensualidades del
    * mes/año seleccionado.
    */
    private void btnMostrarMensualidadesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarMensualidadesActionPerformed
        int mes = cmbMesMostrar.getSelectedIndex() + 1;
    String textoAnio = txtAnioMostrar.getText().trim();

    if (textoAnio.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el año");
        return;
    }

    int anio;
    try {
        anio = Integer.parseInt(textoAnio);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número");
        return;
    }

    String[] columnas = {"Consecutivo", "Núm Alquiler", "Fecha Creación", "Inquilino", "Mes en Cobro", "Año", "Descuento", "Monto a pagar", "Estado"};
    model = new DefaultTableModel(null, columnas);
    tblMensualidades.setModel(model);

    for (Mensualidades m : listaMensualidades) {
        if (m.getMesCobro() == mes && m.getAnioActual() == anio) {
            Object[] fila = {
                m.getConsecutivo(),
                m.getNumAlquiler(),
                m.getFechCreacion(),
                m.getNomInquilino(),
                m.getMesCobro(),
                m.getAnioActual(),
                m.getDescuento() + "%",
                m.getMontoMes(),
                m.getEstado()
            };
            model.addRow(fila);
        }
    }
    }//GEN-LAST:event_btnMostrarMensualidadesActionPerformed

