    /**
     * Reconstruye el modelo de la tabla a partir de la lista de alquileres actual. 
     * Se llama al abrir la ventana y después de cada Nuevo, Editar o Eliminar, para que la tabla siempre refleje los datos vigentes.
     */
    private void cargarTabla() {
        javax.swing.table.DefaultTableModel tabla = new javax.swing.table.DefaultTableModel(
                new Object[]{"Número", "Fecha", "Precio", "Estado"}, 0) {
            @Override
            public boolean isCellEditable(int row, int col) {
                return false;
            }
        };

        for (modelo.Alquileres a : listaAlquileres) {
            tabla.addRow(new Object[]{
                a.getNumAlquiler(),
                a.getFechaContrato(),
                a.getPrecioAlquiler(),
                a.getEstado()
            });
        }

        tblAlquileres.setModel(tabla);
    }

