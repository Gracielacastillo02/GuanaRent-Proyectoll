    /**
     * Toma el alquiler seleccionado en la tabla y abre {@link DlgNewAlquiler}
     * en modo "editar" con esos datos precargados. Si no hay ninguna fila
     * seleccionada, muestra un aviso y no hace nada.
     *
     * @param evt evento de clic sobre el botón Editar
     */
    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblAlquileres.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un alquiler para editar.");
            return;
        }
        modelo.Alquileres seleccionado = listaAlquileres.get(fila);
        DlgNewAlquiler dlg = new DlgNewAlquiler((java.awt.Frame) this.getParent(), true,
                listaAlquileres, listaInquilinos, listaViviendas, seleccionado);
        dlg.setVisible(true);
        cargarTabla();
    }//GEN-LAST:event_btnEditarActionPerformed

    /**
     * Elimina de la lista el alquiler seleccionado en la tabla, previa
     * confirmación del usuario. Si no hay ninguna fila seleccionada,
     * muestra un aviso y no hace nada.
     *
     * @param evt evento de clic sobre el botón Eliminar
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblAlquileres.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un alquiler para eliminar.");
            return;
        }
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Está seguro que desea eliminar este alquiler?", "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            listaAlquileres.remove(fila);
            cargarTabla();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

