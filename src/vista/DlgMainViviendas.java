    /**
     * Carga la tabla con todas las viviendas de la lista.
     */
    public void mostrarDatos() {
        String[] columnas = {"ID", "Descripción", "Dirección", "Propietario", "Precio Base", "Estado"};
        model = new DefaultTableModel(null, columnas);
        tblViviendas.setModel(model);

        for (Vivienda vivienda : listaVivienda) {
            Object[] fila = {
                vivienda.getIdVivienda(),
                vivienda.getDescripcion(),
                vivienda.getDireccion(),
                vivienda.getPropietario(),
                vivienda.getPrecioBase(),
                vivienda.getEstado()
            };
            model.addRow(fila);
        }
    }

    /**
     * Filtra la tabla según el texto escrito en txtBuscar, comparando contra el id de la vivienda y su descripción.
     */
    private void filtrar() {
        String texto = txtBuscar.getText().trim().toLowerCase();

        model = new DefaultTableModel(null, new String[]{"ID", "Descripción", "Dirección", "Propietario", "Precio Base", "Estado"});
        tblViviendas.setModel(model);

        for (Vivienda vivienda : listaVivienda) {
            boolean coincideId = String.valueOf(vivienda.getIdVivienda()).contains(texto);
            boolean coincideDescripcion = vivienda.getDescripcion().toLowerCase().contains(texto);

            if (texto.isEmpty() || coincideId || coincideDescripcion) {
                Object[] fila = {
                    vivienda.getIdVivienda(),
                    vivienda.getDescripcion(),
                    vivienda.getDireccion(),
                    vivienda.getPropietario(),
                    vivienda.getPrecioBase(),
                    vivienda.getEstado()
                };
                model.addRow(fila);
            }
        }
    }

