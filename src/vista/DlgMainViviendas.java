    /**
     * Abre DlgNewVivienda en modo Editar con la vivienda seleccionada en la tabla.
     *
     * @param evt evento de clic sobre el botón Editar
     */
    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblViviendas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una vivienda de la tabla");
            return;
        }
        Vivienda viviendaSeleccionada = listaVivienda.get(fila);
        DlgNewVivienda dlg = new DlgNewVivienda(null, true, listaVivienda, listaProp, 2, viviendaSeleccionada, fila);
        dlg.setVisible(true);
        mostrarDatos();
    }//GEN-LAST:event_btnEditarActionPerformed

    /**
     * Elimina la vivienda seleccionada en la tabla, también lanza mensaje de confirmación antes.
     *
     * @param evt evento de clic sobre el botón Eliminar
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblViviendas.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una vivienda de la tabla");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this,
                "¿Está seguro de eliminar esta vivienda?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            listaVivienda.remove(fila);
            mostrarDatos();
            JOptionPane.showMessageDialog(this, "Vivienda eliminada");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

